#!/usr/bin/env node
// Regenerates create-template.mjs: a single, dependency-free script that
// recreates every git-tracked file of this template in the current directory.
//
// Usage (from anywhere):  node scripts/generate-installer.mjs
//
// File contents are read from the git index (`git show :path`), so the output
// is LF-normalised regardless of core.autocrlf, and untracked files are never
// picked up.

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outFile = join(root, "create-template.mjs");

// Tooling around the template, not part of it.
const EXCLUDED = new Set(["create-template.mjs", "scripts/generate-installer.mjs"]);

const git = (...args) => execFileSync("git", ["-C", root, ...args], { maxBuffer: 64 * 1024 * 1024 });

const paths = git("ls-files", "-z")
  .toString("utf8")
  .split("\0")
  .filter((p) => p && !EXCLUDED.has(p));

const decoder = new TextDecoder("utf-8", { fatal: true });

const entries = paths.map((path) => {
  const buf = git("show", `:${path}`);
  try {
    if (buf.includes(0)) throw new Error("binary");
    return [path, { text: decoder.decode(buf) }];
  } catch {
    return [path, { base64: buf.toString("base64") }];
  }
});

const body = entries
  .map(([path, content]) => `  ${JSON.stringify(path)}: ${JSON.stringify(content)},`)
  .join("\n");

const output = `#!/usr/bin/env node
// Generated by scripts/generate-installer.mjs - do not edit by hand.
//
// Recreates the ultra-extension-template in the current directory.
//
//   node create-template.mjs            write the files (aborts if any already exist)
//   node create-template.mjs --force    overwrite existing files

import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve, sep } from "node:path";

const FILES = {
${body}
};

const args = process.argv.slice(2);

if (args.includes("--help") || args.includes("-h")) {
  console.log("Usage: node create-template.mjs [--force]");
  process.exit(0);
}

const unknown = args.filter((a) => a !== "--force");
if (unknown.length > 0) {
  console.error(\`Unknown option: \${unknown.join(" ")}\\nUsage: node create-template.mjs [--force]\`);
  process.exit(1);
}

const force = args.includes("--force");
const target = resolve(process.cwd());
const paths = Object.keys(FILES);

// Never write outside the target directory.
const resolved = paths.map((p) => {
  const abs = resolve(target, p);
  if (!abs.startsWith(target + sep)) throw new Error(\`Refusing to write outside the target: \${p}\`);
  return abs;
});

if (!force) {
  const existing = paths.filter((_, i) => existsSync(resolved[i]));
  if (existing.length > 0) {
    console.error(\`Nothing written. These files already exist (use --force to overwrite):\\n\${existing.map((p) => \`  \${p}\`).join("\\n")}\`);
    process.exit(1);
  }
}

paths.forEach((p, i) => {
  const { text, base64 } = FILES[p];
  mkdirSync(dirname(resolved[i]), { recursive: true });
  writeFileSync(resolved[i], text ?? Buffer.from(base64, "base64"));
  console.log(\`  created \${p}\`);
});

console.log(\`\\nWrote \${paths.length} files to \${target}\\nNext: pnpm install\`);
`;

writeFileSync(outFile, output);
console.log(`Wrote ${outFile} (${entries.length} files, ${(output.length / 1024).toFixed(1)} KB)`);
